/**
 * Inter, bundled as static weights 400/500/600 only (Section 4.2). Fallback to
 * platform Roboto happens automatically if a glyph is missing from the Latin +
 * Latin-Ext + ₹ subset.
 */
val InterFontFamily = FontFamily(
    Font(R.font.inter_regular, FontWeight.Normal),
    Font(R.font.inter_medium, FontWeight.Medium),
    Font(R.font.inter_semibold, FontWeight.SemiBold),
)

/** Tabular figures so dates, counts, amounts and countdowns don't jitter as digits change. */
fun TextStyle.tabularNums(): TextStyle = copy(fontFeatureSettings = "tnum")

